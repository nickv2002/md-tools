export function generateSequences(n: number, seed: number): string[] {
  const r = mulberry32(seed)
  const out: string[] = []
  for (let i = 0; i < n; i++) {
    const len = 1 + Math.floor(r() * 6)
    let s = ''
    for (let k = 0; k < len; k++)
      s += String.fromCodePoint(POOL[Math.floor(r() * POOL.length)]!)
    out.push(s)
  }
  return out
}
